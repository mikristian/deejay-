const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/../music-hub/top-decks-waveform.js','utf8');
const audios=[];
const document={readyState:'loading',addEventListener(){},getElementById(){return null;},createElement(type){
  assert.equal(type,'audio');
  const a={paused:true,ended:false,readyState:1,volume:1,currentTime:0,duration:180,playbackRate:1,
    callbacks:{},addEventListener(name,fn){(this.callbacks[name]??=[]).push(fn);},
    emit(name){for(const fn of this.callbacks[name]||[])fn();},
    removeAttribute(){},load(){},pause(){this.paused=true;this.emit('pause');},
    play(){this.paused=false;this.emit('play');return Promise.resolve();}};
  audios.push(a);return a;
}};
const window={addEventListener(){},requestAnimationFrame(){return 1;}};
vm.runInNewContext(source,{window,document,Map,Set,Math,Number,Promise,Date,
  setInterval,clearInterval,fetch:()=>Promise.resolve({ok:true,json:async()=>({markers:[]})})});
const d=window.MusicHubTopDecks;
const stage=(deck,id,bpm)=>d.setDeck(deck,{track:{id,length:180,bpm}});
stage(1,101,120);stage(2,102,100);
assert.equal(d.preloadDeck(1),true);
assert.equal(d.preloadDeck(2),true);
assert.equal(d.syncDeck(2),true);
assert.equal(d.mixerState().tempo[1],.7,'100 BPM deck should run 1.2x for 120 BPM sync');
assert.equal(d.syncDeck(3),false);
assert.equal(d.cueDeck(1),true,'first cue press at zero should play');
assert.equal(audios[0].paused,false);
assert.equal(d.cueDeck(1),true,'playing cue should pause and return to cue');
assert.equal(audios[0].paused,true);
assert.equal(d.seekDeck(0,.2),true);
assert.equal(d.cueDeck(1),true,'paused cue press at new time should place cue');
assert.ok(Math.abs(d.localStatus().deckControls[0].cuePoint-36)<.001);
assert.equal(d.cueDeck(1),true,'second cue press at same position starts playback');
assert.equal(audios[0].paused,false);
assert.equal(d.cueDeck(1),true);
assert.ok(Math.abs(audios[0].currentTime-36)<.001);
assert.equal(d.triggerHotCue(1,0,false),true);
assert.equal(d.seekDeck(0,.5),true);
assert.equal(d.triggerHotCue(1,0,false),true);
assert.ok(Math.abs(audios[0].currentTime-36)<.001,'hot cue returns to stored timestamp');
assert.equal(d.triggerHotCue(1,0,true),true);
assert.equal(d.triggerHotCue(1,0,true),false,'deleted pad stays empty');
assert.equal(d.triggerHotCue(1,8),false);
assert.equal(d.beatJump(1,4),true,'forward one beat');
assert.ok(Math.abs(audios[0].currentTime-36.5)<.001);
assert.equal(d.beatJump(1,0),true,'back one beat');
assert.ok(Math.abs(audios[0].currentTime-36)<.001);
assert.equal(d.beatJump(1,4,true),true,'shift multiplies jump size');
assert.ok(Math.abs(audios[0].currentTime-38)<.001);
assert.equal(d.loopIn(1),true);
assert.equal(d.loopOut(1),false,'out cannot equal in');
assert.equal(d.seekDeck(0,39/180),true);
assert.equal(d.loopOut(1),true);
assert.equal(d.localStatus().deckControls[0].loop.active,true);
assert.equal(d.loopHalf(1),true);
assert.ok(Math.abs(d.localStatus().deckControls[0].loop.end-38.5)<.001);
assert.equal(d.loopDouble(1),true);
assert.equal(d.playDeck(1),true);
audios[0].currentTime=39.1;audios[0].emit('timeupdate');
assert.ok(audios[0].currentTime>=38&&audios[0].currentTime<39,'loop must wrap real playing audio');
assert.equal(d.loopExit(1),true);
assert.equal(d.loopExit(1),false);
assert.equal(d.loopFourBeat(1),true);
assert.ok(Math.abs(d.localStatus().deckControls[0].loop.end-d.localStatus().deckControls[0].loop.start-2)<.001);
assert.equal(d.beatLoop(1,0),true);
assert.ok(Math.abs(d.localStatus().deckControls[0].loop.end-d.localStatus().deckControls[0].loop.start-.125)<.001);
assert.equal(d.beatLoop(1,7,true),true);
assert.equal(d.beatLoop(1,-1),false);
stage(2,103,0);
assert.equal(d.syncDeck(1),false,'missing BPM cannot be synced');
