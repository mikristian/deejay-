assert.equal(d.loopFourBeat(2),false);
stage(1,111,130);
assert.equal(d.localStatus().deckControls[0].loop,null,'new track resets loop');
assert.equal(d.localStatus().deckControls[0].hotCues[0],null,'new track resets hot cues');
stage(1,111,130);
assert.equal(d.localStatus().deckControls[0].cuePoint,0);
stage(1,111,130);d.setDeck(1,{track:{id:111,length:180,bpm:130},verified:true});
