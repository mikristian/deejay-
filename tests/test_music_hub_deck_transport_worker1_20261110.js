assert.equal(d.loopFourBeat(1),false);
assert.equal(d.triggerHotCue(1,0),false);
console.log('PASS cue, BPM sync, loop in/out/half/double/4beat, real audio loop wrap, hot cue, beat jump, beat loop and verified guards');
